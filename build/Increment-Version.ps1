param(
    [Parameter(Mandatory = $true)][string]$VersionFile,
    [Parameter(Mandatory = $true)][string]$HeaderPath
)

$ErrorActionPreference = 'Stop'
$versionPath = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($VersionFile)
$generatedPath = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($HeaderPath)
[System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($generatedPath)) | Out-Null

# Serialize reservations across configurations. Never reset a missing counter.
$counter = $null
$deadline = [DateTime]::UtcNow.AddSeconds(20)
while ($null -eq $counter) {
    try {
        $counter = [System.IO.File]::Open($versionPath, [System.IO.FileMode]::Open,
            [System.IO.FileAccess]::ReadWrite, [System.IO.FileShare]::None)
    }
    catch [System.IO.IOException] {
        if (-not [System.IO.File]::Exists($versionPath) -or [DateTime]::UtcNow -ge $deadline) { throw }
        Start-Sleep -Milliseconds 100
    }
}
try {
    $bytes = New-Object byte[] ([int]$counter.Length)
    $read = $counter.Read($bytes, 0, $bytes.Length)
    $current = [System.Text.Encoding]::UTF8.GetString($bytes, 0, $read).Trim().TrimStart([char]0xFEFF)
    if ($current -notmatch '^(\d+)\.(\d+)\.(\d+)$') {
        throw "Version invalida en ${versionPath}: '$current'. Se esperaba mayor.menor.parche."
    }
    $major = [int]$Matches[1]
    $minor = [int]$Matches[2]
    $patch = [int]$Matches[3]
    if ($major -gt 65535 -or $minor -gt 65535 -or $patch -gt 65535) {
        throw 'Los componentes de version deben estar entre 0 y 65535.'
    }
    # VERSIONINFO stores each component in an unsigned 16-bit value.
    if ($patch -eq 65535) {
        $patch = 0
        if ($minor -eq 65535) { $minor = 0; ++$major } else { ++$minor }
    } else { ++$patch }
    if ($major -gt 65535) { throw 'Se agoto el rango de versiones admitido por Windows.' }
    $version = "$major.$minor.$patch"
    $header = @"
// Generated by build/Increment-Version.ps1. Do not edit.
#pragma once
#define APP_VERSION_STRING "$version"
#define APP_WINDOW_TITLE L"AppUnlock - ver $version"
#define APP_VERSION_RESOURCE $major,$minor,$patch,0
"@
    [System.IO.File]::WriteAllText($generatedPath, $header + "`r`n", [System.Text.Encoding]::ASCII)
    $next = [System.Text.Encoding]::UTF8.GetBytes($version + "`r`n")
    $counter.Position = 0
    $counter.Write($next, 0, $next.Length)
    $counter.SetLength($next.Length)
    $counter.Flush($true)
    Write-Output "AppUnlock - ver $version"
}
finally {
    $counter.Dispose()
}
